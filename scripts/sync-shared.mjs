#!/usr/bin/env node
/**
 * Copies the shared AeroFMS packages from the AreoFMS-Web repository into ./packages.
 * The FMS core lives in AreoFMS-Web; Android vendors a pinned copy so it builds standalone.
 *
 *   node scripts/sync-shared.mjs [--web ../Web] [--check]
 *
 * --check exits with code 1 when the vendored copy differs from the Web repository (CI).
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const webIdx = args.indexOf('--web')
const webRoot = resolve(root, webIdx >= 0 ? args[webIdx + 1] : '../Web')
const check = args.includes('--check')
const PACKAGES = ['shared', 'navigation', 'core', 'aircraft', 'simulation', 'training', 'i18n', 'ui', 'cloud']

function files(dir) {
  const out = []
  for (const f of readdirSync(dir)) {
    const p = join(dir, f)
    if (statSync(p).isDirectory()) out.push(...files(p))
    else out.push(p)
  }
  return out
}

function digest(dir) {
  const h = createHash('sha256')
  for (const f of files(dir).sort()) {
    h.update(relative(dir, f))
    h.update(readFileSync(f))
  }
  return h.digest('hex')
}

function transformPackageJson(text) {
  const pkg = JSON.parse(text)
  for (const field of ['dependencies', 'devDependencies']) {
    for (const [k, v] of Object.entries(pkg[field] ?? {})) {
      if (typeof v === 'string' && v.startsWith('workspace:')) pkg[field][k] = '*'
    }
  }
  return `${JSON.stringify(pkg, null, 2)}\n`
}

if (!existsSync(join(webRoot, 'packages'))) {
  console.error(`AreoFMS-Web not found at ${webRoot}`)
  process.exit(2)
}

let differs = false
for (const name of PACKAGES) {
  const src = join(webRoot, 'packages', name)
  const dst = join(root, 'packages', name)
  if (check) {
    const a = digest(join(src, 'src'))
    const b = existsSync(join(dst, 'src')) ? digest(join(dst, 'src')) : ''
    if (a !== b) {
      console.error(`packages/${name} is out of date`)
      differs = true
    }
    continue
  }
  rmSync(dst, { recursive: true, force: true })
  mkdirSync(dst, { recursive: true })
  cpSync(join(src, 'src'), join(dst, 'src'), { recursive: true })
  writeFileSync(join(dst, 'package.json'), transformPackageJson(readFileSync(join(src, 'package.json'), 'utf8')))
  console.log(`synced packages/${name}`)
}
if (!check) {
  writeFileSync(join(root, 'packages', 'SYNCED_FROM.txt'), `Generated by scripts/sync-shared.mjs from AreoFMS-Web. Do not edit here.\n${new Date().toISOString()}\n`)
}
process.exit(differs ? 1 : 0)
